const archive = document.getElementById("archive");

const doc = document.getElementById("document");

const content = document.getElementById("docContent");



function loadCards(list=LAD){


archive.innerHTML="";


list.forEach(obj=>{


let card=document.createElement("div");


card.className="card";


card.innerHTML=`

<h2>${obj.id}</h2>

<p>${obj.name}</p>

<p class="class">

Класс:
${obj.class}

</p>


<p class="status">

${obj.status}

</p>


<button>

Открыть

</button>

`;



card.onclick=()=>openDoc(obj);



archive.appendChild(card);


});


}




// ==============================
// ОТКРЫТИЕ ДОКУМЕНТА
// ==============================


function openDoc(obj){


clickSound.play();



let access=
Number(document.getElementById("level").value);



if(access < obj.level){


content.innerHTML=`

<h1>${obj.id}</h1>


<div class="warning">

ДОСТУП ЗАПРЕЩЁН

<br><br>

Требуется уровень:
${obj.level}

</div>

`;



}

else{


content.innerHTML=obj.text;


typing.play();


}



archive.style.display="none";

doc.style.display="block";


}




function back(){


doc.style.display="none";

archive.style.display="grid";


}




